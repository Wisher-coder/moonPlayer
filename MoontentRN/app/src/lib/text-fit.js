// ============================================================================
// text-fit.js —— 系统字体缩放（fontScale）上限常量（三端排版策略）
// ----------------------------------------------------------------------------
// 背景（安卓专属坑）：Android 系统「字体大小/显示大小」>1 时所有 Text 按比例
// 放大，而定宽/定高容器（176px 历史卡、168px 缩略 + flex 文案列、32/40px 高
// 的 chip/胶囊、20px 高的时长角标……）不会随之变大 → 密集卡片文字普遍重度
// 换行/溢出。web 端无字体缩放机制，网页上永远「正常」，native 才暴露。
// 策略（与 YouTube App 同思路，保留无障碍底线）：
//   - 密集定尺寸文本（卡片标题/meta/角标/按钮/设置行）设 maxFontSizeMultiplier
//     上限：标题类 FSM_DENSE=1.4、辅助信息类 FSM_META=1.2；
//   - 长文（描述盒展开内容、Dialog、关于节、错误文案）【不设限】，完全跟随
//     系统缩放——自由容器会自然换行，不构成破坏；
//   - 配合 includeFontPadding:false（安卓默认字体内边距会把紧凑行盒顶歪，
//     见 ui/Button 的先例）统一三端文字盒度量。
// 用法：密集文本的 <Text> 上加 maxFontSizeMultiplier={FSM_DENSE}；新写密集
// 控件时同样引用本常量，不要再裸写数字（全站一个口径）。
// ============================================================================
export const FSM_DENSE = 1.4; // 标题类：卡片标题、包名、作者名、按钮/设置行文字
export const FSM_META = 1.2; // 辅助类：时长角标、meta 行、计数、站名、序号
